"""Build browser-readable content from pages/**/*.md. Run with --watch for local editing."""
from pathlib import Path
import argparse,ast,datetime,json,time
ROOT=Path(__file__).resolve().parents[1]
CATEGORIES=('publications','activities','projects')

def split_inline_list(value):
 parts=[]
 current=[]
 quote=None
 for char in value:
  if char in ('"', "'"):
   if quote is None:quote=char
   elif quote==char:quote=None
   current.append(char)
  elif char==',' and quote is None:
   parts.append(''.join(current).strip())
   current=[]
  else:current.append(char)
 parts.append(''.join(current).strip())
 return parts

def parse_scalar(value):
 value=value.strip()
 if value=='' or value.lower() in ('null','~'):return None
 if value.lower()=='true':return True
 if value.lower()=='false':return False
 if value.startswith('[') and value.endswith(']'):
  inner=value[1:-1].strip()
  return [] if not inner else [parse_scalar(item) for item in split_inline_list(inner)]
 if len(value)>=2 and value[0]==value[-1] and value[0] in ('"', "'"):
  try:return ast.literal_eval(value)
  except (SyntaxError,ValueError):return value[1:-1]
 return value

def parse_front_matter(text,file):
 """Parse the flat YAML subset used by this site's Markdown headers."""
 meta={}
 for line_number,line in enumerate(text.splitlines(),start=2):
  if not line.strip() or line.lstrip().startswith('#'):continue
  if line[:1].isspace():
   raise ValueError(f'{file}:{line_number}: nested YAML is not supported')
  if ':' not in line:
   raise ValueError(f'{file}:{line_number}: expected key: value')
  key,value=line.split(':',1)
  key=key.strip()
  if not key:raise ValueError(f'{file}:{line_number}: empty YAML key')
  meta[key]=parse_scalar(value)
 return meta

def build():
 entries=[]
 for category in CATEGORIES:
  for file in sorted((ROOT/'pages'/category).rglob('*.md')):
   if file.name.startswith(('_','.')) or file.name.lower()=='readme.md':continue
   raw=file.read_text(encoding='utf-8-sig').replace('\r\n','\n')
   if not raw.startswith('---\n'):raise ValueError(f'{file}: missing YAML front matter')
   parts=raw.split('\n---',1)
   if len(parts)!=2:raise ValueError(f'{file}: missing closing ---')
   meta=parse_front_matter(parts[0][4:],file)
   if 'template' in (meta.get('navs') or []) or meta.get('draft') is True:continue
   meta['title'] = meta.get('title') or meta.get('name')
   if not meta.get('title'):raise ValueError(f'{file}: title or name required')
   date=str(meta.get('date') or (file.name[:10] if len(file.name)>10 and file.name[4]=='-' and file.name[7]=='-' else ''))
   if date:
    try:datetime.date.fromisoformat(date)
    except ValueError:raise ValueError(f'{file}: date must be YYYY-MM-DD')
   entry={**meta,'date':date,'category':category,'id':category+'/'+file.relative_to(ROOT/'pages'/category).with_suffix('').as_posix(),'body':parts[1].lstrip('\n'),'file':file.relative_to(ROOT).as_posix()}
   entries.append(entry)
 entries.sort(key=lambda e:(e['date'],e['title']),reverse=True)
 value='// Generated by scripts/build_content.py; edit pages/**/*.md instead.\nwindow.PAGE_CONTENT = '+json.dumps(entries,ensure_ascii=False,default=str,indent=2)+';\n'
 out=ROOT/'content-index.js'
 if not out.exists() or out.read_text(encoding='utf-8')!=value:out.write_text(value,encoding='utf-8');print(f'Indexed {len(entries)} entries',flush=True)
 return entries
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--watch',action='store_true');args=parser.parse_args();build()
 if args.watch:
  print('Watching pages/; Ctrl+C to stop.',flush=True)
  while True:
   time.sleep(1)
   try:build()
   except Exception as error:print(error,flush=True)
